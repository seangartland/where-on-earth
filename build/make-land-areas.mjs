/**
 * Build-time: assets/country-outlines.topo.json + assets/us-states.topo.json
 * -> assets/land-areas.json, spherical (Chamberlain-Duquette) polygon areas
 * in km2 for every country key AND every state key, computed on the
 * shipped topo geometries (the game's own geometry is the source of truth
 * for this stat, not an external land-area dataset; conventions differ,
 * see the validation table below).
 *
 * Report: docs/land-areas-report.md, with Russia, France, Texas and
 * California checked against commonly cited real-world land areas.
 *
 * usage: node build/make-land-areas.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const DEG = Math.PI / 180;
const R = 6371.0088; // mean Earth radius, km (same constant as src/globe/outlines.js distanceKm)

function decode(topo) {
  const { scale, translate } = topo.transform;
  const k = 1 / scale[0];
  const tx = Math.round(translate[0] * k);
  const ty = Math.round(translate[1] * k);
  const arcs = topo.arcs.map((arc) => {
    let x = 0, y = 0;
    return arc.map(([dx, dy]) => [((x += dx) + tx) / k, ((y += dy) + ty) / k]);
  });
  const ring = (refs) => {
    const pts = [];
    for (const i of refs) {
      const arc = i >= 0 ? arcs[i] : arcs[~i].slice().reverse();
      for (let j = pts.length ? 1 : 0; j < arc.length; j++) pts.push(arc[j]);
    }
    return pts;
  };
  const units = topo.objects.data.geometries.map((g) => ({
    id: g.id,
    polys: (g.type === "Polygon" ? [g.arcs] : g.arcs).map((poly) => poly.map(ring)),
  }));
  return { units, keys: topo.keys };
}

// Longitude unwrap matching src/globe/surface.js unwrap(): a ring that
// crosses the antimeridian (Alaska, Russia, Fiji) is shifted continuous
// rather than jumping ~360 deg, so its spherical area comes out right.
function unwrap(pts) {
  const out = [];
  let off = 0, prev = null;
  for (const [lon, lat] of pts) {
    let L = lon + off;
    if (prev !== null) {
      if (L - prev > 180) { off -= 360; L -= 360; }
      else if (L - prev < -180) { off += 360; L += 360; }
    }
    out.push([L, lat]);
    prev = L;
  }
  return out;
}

// Chamberlain-Duquette spherical excess formula, km2, on a closed ring.
function ringAreaKm2(ring) {
  const u = unwrap(ring);
  let sum = 0;
  for (let i = 0; i < u.length - 1; i++) {
    const [lng1, lat1] = u[i], [lng2, lat2] = u[i + 1];
    sum += (lng2 - lng1) * DEG * (2 + Math.sin(lat1 * DEG) + Math.sin(lat2 * DEG));
  }
  return Math.abs((sum * R * R) / 2);
}

function polyAreaKm2(poly) {
  return poly.reduce((n, ring, i) => n + (i === 0 ? ringAreaKm2(ring) : -ringAreaKm2(ring)), 0);
}

function unitAreaKm2(unit) {
  return unit.polys.reduce((n, poly) => n + polyAreaKm2(poly), 0);
}

const countryTopo = JSON.parse(readFileSync("assets/country-outlines.topo.json", "utf8"));
const statesTopo = JSON.parse(readFileSync("assets/us-states.topo.json", "utf8"));
const countries = decode(countryTopo);
const states = decode(statesTopo);

function keyAreas(data) {
  const byId = new Map(data.units.map((u) => [u.id, unitAreaKm2(u)]));
  const out = {};
  for (const [key, ids] of Object.entries(data.keys)) out[key] = ids.reduce((n, id) => n + (byId.get(id) || 0), 0);
  return out;
}

const countryAreas = keyAreas(countries);
const stateAreas = keyAreas(states);
const out = { countries: countryAreas, states: stateAreas };
const OUT = "assets/land-areas.json";
writeFileSync(OUT, JSON.stringify(out));

// ---- validate against commonly cited real-world land areas ----------------
// Real-world figures are themselves convention-dependent (coastline detail,
// inland water, disputed areas); these are standard references, used only to
// sanity-check this file's own geometry, not to correct it.
const CHECKS = [
  { label: "Russia", measured: countryAreas["Russia"], real: 17098242 },
  // Natural Earth's FRA admin-0 unit already includes the overseas
  // departments (French Guiana, Reunion, Guadeloupe, Martinique, Mayotte);
  // MEMBERS (build/make-country-outlines.mjs) adds the two collectivities
  // (New Caledonia, French Polynesia) it ships as separate units. 643,801
  // km2 is the commonly cited total for France including every overseas
  // region and collectivity.
  { label: "France (all overseas regions + collectivities)", measured: countryAreas["France"], real: 643801 },
  { label: "Texas", measured: stateAreas["US-TX"], real: 695662 },
  { label: "California", measured: stateAreas["US-CA"], real: 423967 },
];
const rows = CHECKS.map((c) => ({ ...c, deltaPct: ((c.measured - c.real) / c.real) * 100 }));

const KB = (n) => `${(n / 1024).toFixed(0)} KB`;
const raw = Buffer.byteLength(JSON.stringify(out));
const md = `# Land areas build report

Generated by \`node build/make-land-areas.mjs\` on ${new Date().toISOString().slice(0, 10)}. Spherical (Chamberlain-Duquette) polygon areas computed on this repo's own shipped geometry (assets/country-outlines.topo.json, assets/us-states.topo.json), not an external land-area dataset. Land area conventions vary (coastline detail, inland water, disputed territory, Simplify/DP tolerance); the deltas below are a sanity check on this file's own geometry, not a correction target.

## Output

- \`${OUT}\`: ${KB(raw)} (${raw.toLocaleString("en-US")} B). ${Object.keys(countryAreas).length} country keys, ${Object.keys(stateAreas).length} state keys.

## Validation (measured on this file vs. commonly cited real-world land area)

| place | measured km2 | reference km2 | delta |
|---|---|---|---|
${rows.map((r) => `| ${r.label} | ${r.measured.toLocaleString("en-US", { maximumFractionDigits: 0 })} | ${r.real.toLocaleString("en-US")} | ${r.deltaPct.toFixed(1)}% |`).join("\n")}

France's key is metropolitan France plus every overseas department NE already bundles into its FRA unit (French Guiana, Reunion, Guadeloupe, Martinique, Mayotte) plus the two collectivities MEMBERS adds (New Caledonia, French Polynesia; see build/make-country-outlines.mjs), so it is well above mainland France's commonly cited 551,695 km2 alone; the reference row above is the total most commonly cited for France including every overseas region and collectivity.
`;
writeFileSync("docs/land-areas-report.md", md);
