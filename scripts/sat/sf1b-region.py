#!/usr/bin/env python3
"""Write src/globe/sf1b-region.js: the tiles of the Phase 3 pilot region.

The region is the pilot's own window set (eox1-work
shots/sat-review/seamfix-v4/pilot3/windows.json, 228 windows) expanded to the
tiles each window lists in the render plan (scripts/sat/work/s2gm2025/
full-plan.json): 1159 tiles at z4-z9, as in docs/pilot3-report-2026-10-31.md.
Every one is checked against the pilot's GET+sha256 record of the
s2gm2025-sf1b/ upload (r2-verified-b.json).

Usage: python3 scripts/sat/sf1b-region.py [eox1-work dir]
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

work = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / 'workspace/map-game/eox1-work')
p3 = work / 'shots/sat-review/seamfix-v4/pilot3'
plan = {w['id']: w for w in json.load(open(work / 'scripts/sat/work/s2gm2025/full-plan.json'))['windows']}
ids = json.load(open(p3 / 'windows.json'))
tiles = {(plan[i]['z'], t['x'], t['y']) for i in ids for t in plan[i]['tiles']}
assert len(ids) == 228 and len(tiles) == 1159, (len(ids), len(tiles))
verified = json.load(open(p3 / 'r2-verified-b.json'))
missing = [t for t in tiles if 's2gm2025-sf1b/%d/%d/%d.jpg' % t not in verified]
assert not missing, missing[:5]

# One entry per 'z/y' row: inclusive x runs, flattened [x0, x1, x0, x1, ...].
rows = defaultdict(list)
for z, x, y in sorted(tiles):
    r = rows[f'{z}/{y}']
    if r and r[-1] == x - 1:
        r[-1] = x
    else:
        r += [x, x]
lines = ''.join(f"  '{k}': [{', '.join(map(str, v))}],\n" for k, v in rows.items())

out = Path(__file__).resolve().parents[2] / 'src/globe/sf1b-region.js'
out.write_text(f"""// Generated by scripts/sat/sf1b-region.py; do not edit.
// The Phase 3 pilot region (eox1-work docs/pilot3-report-2026-10-31.md): the
// {len(tiles)} z4-z9 tiles of its {len(ids)} windows, every one in the
// s2gm2025-sf1b/ upload. Rows are 'z/y': inclusive x runs [x0, x1, ...].
const ROWS = {{
{lines}}};

export const inSf1bRegion = (z, x, y) => {{
  const r = ROWS[`${{z}}/${{y}}`];
  if (r) for (let i = 0; i < r.length; i += 2) if (x >= r[i] && x <= r[i + 1]) return true;
  return false;
}};
""")
print(f'{out}: {len(tiles)} tiles, {len(rows)} rows')
