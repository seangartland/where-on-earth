"""Derive the World Capitals pack set (2026-10-29).

For each country in assets/locations.json (cities only), find the bank entry
that is its capital, using the mledoze/countries reference (capital field)
and name matching. Writes src/meta/pack-capitals.js, which the game imports;
nothing is fetched at runtime.

Run: python3 scripts/pack-capitals/derive.py <path to mledoze countries.json>
Reference: https://raw.githubusercontent.com/mledoze/countries/master/countries.json
"""
import json
import sys
import unicodedata

# Bank country names the reference spells differently.
COUNTRY_ALIASES = {'Cabo Verde': 'Cape Verde', 'Turkey': 'Türkiye'}
# Countries the reference has no entry for: UK constituent countries.
MANUAL_CAPITALS = {'England': ['London'], 'Scotland': ['Edinburgh'], 'Wales': ['Cardiff'], 'Northern Ireland': ['Belfast']}
# Ambiguous cases, resolved by hand. Spelling variants of the reference name:
# Saint John's/St. John's, South Tarawa/Tarawa, Luxembourg/Luxembourg City,
# Ulan Bator/Ulaanbaatar, Naypyidaw/Nay Pyi Taw, City of San Marino/San Marino,
# Sana'a/Sanaa, New Delhi/Delhi (the bank's Delhi entry covers New Delhi).
# Choices: Equatorial Guinea's reference capital Ciudad de la Paz is not yet
# the working capital, Malabo is; Eswatini takes Mbabane (executive) over
# Lobamba (royal and legislative); South Africa takes Pretoria (executive)
# of its three; Bolivia keeps the reference's Sucre (constitutional) over
# La Paz (seat of government).
CAPITAL_OVERRIDES = {
    'Antigua and Barbuda': ["St. John's"], 'Kiribati': ['Tarawa'], 'Luxembourg': ['Luxembourg City'],
    'Mongolia': ['Ulaanbaatar'], 'Myanmar': ['Nay Pyi Taw'], 'San Marino': ['San Marino'], 'Yemen': ['Sanaa'],
    'India': ['Delhi'], 'Equatorial Guinea': ['Malabo'], 'Eswatini': ['Mbabane'], 'South Africa': ['Pretoria'],
}


def norm(text):
    text = ''.join(c for c in unicodedata.normalize('NFKD', text) if not unicodedata.combining(c)).lower()
    for ch in ".,'’-":
        text = text.replace(ch, ' ')
    return ' '.join(text.split())


def playable(item):
    image = item.get('image')
    if not isinstance(image, str) or not image or 'No_image_available' in image:
        return False
    if isinstance(item.get('lat'), (int, float)) and item['lat'] < -60:
        return False
    return 'antarctica' not in str(item.get('country', '')).lower()


def main(ref_path):
    bank = json.load(open('assets/locations.json'))
    ref = json.load(open(ref_path))
    by_name = {}
    for entry in ref:
        for name in [entry['name']['common'], entry['name']['official'], *entry.get('altSpellings', [])]:
            by_name.setdefault(norm(name), entry)
    ids, misses, notes = [], [], []
    for country in sorted({item['country'] for item in bank}):
        if country in CAPITAL_OVERRIDES:
            capitals = CAPITAL_OVERRIDES[country]
        elif country in MANUAL_CAPITALS:
            capitals = MANUAL_CAPITALS[country]
        else:
            entry = by_name.get(norm(COUNTRY_ALIASES.get(country, country)))
            if not entry:
                misses.append(f'{country}: not in the reference')
                continue
            capitals = entry['capital']
        wanted = {norm(name) for name in capitals}
        hits = [item for item in bank if item['country'] == country
                and wanted & {norm(item['short']), norm(item['clue'].split(',')[0])}]
        if len(hits) != 1:
            misses.append(f'{country}: capital {capitals} not in the bank' if not hits else f'{country}: {len(hits)} matches')
            continue
        if not playable(hits[0]):
            notes.append(f'{country}: {hits[0]["id"]} is not playable')
        ids.append(hits[0]['id'])
    body = ',\n'.join(f"  '{i}'" for i in sorted(ids))
    with open('src/meta/pack-capitals.js', 'w') as out:
        out.write(
            '// The World Capitals pack set (2026-10-29): for each country in\n'
            '// assets/locations.json, the city entry that is its capital. Generated by\n'
            '// scripts/pack-capitals/derive.py from the mledoze/countries reference;\n'
            '// see that script for the ambiguous cases and how each was resolved.\n'
            f'export const PACK_CAPITAL_IDS = new Set([\n{body},\n]);\n')
    print(len(ids), 'capitals')
    for line in misses + notes:
        print(line)


main(sys.argv[1])
